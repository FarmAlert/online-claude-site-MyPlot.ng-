create table admins (
  id         uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  user_id    uuid not null unique references auth.users(id),
  name       text not null,
  email      text not null
);

comment on table admins is 'Staff with full view/edit access to every table. Rows are added manually via the Supabase dashboard only, never through public signup.';


-- ---------- 7. ESCROW TRACKING ----------
-- MyPlot is NOT a deposit-taking bank (see Terms of Use, Clause 7) and this
-- table does NOT move money. It is a manual staff tracking layer sitting on
-- top of a real bank account: the buyer wires the purchase sum to MyPlot's
-- bank account, staff manually confirm the transfer arrived (by checking the
-- bank statement/app), mark it here, hold it until the transaction closes,
-- then release it, deducting MyPlot's fees at source per the Terms of Use.
-- No payment gateway or automated bank integration exists yet, this is the
-- record-keeping/status layer requested so that stage can be added later
-- without changing how staff work day to day.
--
-- MyPlot's receiving account (shown to the buyer once a sale is agreed,
-- together with the reference_code below so staff can match the transfer):
--   Account name:   MyPlot.NG
--   Account number: 9652683212
--   Bank:           Providus Bank

create table escrow_transactions (
  id                    uuid primary key default gen_random_uuid(),
  created_at            timestamptz not null default now(),
  reference_code        text not null unique,   -- auto-generated, quote this on the bank transfer

  sell_submission_id    uuid references sell_submissions(id),  -- the listing being sold
  buyer_inquiry_id      uuid references buy_inquiries(id),     -- the buyer paying in
  buyer_name            text not null,
  buyer_phone           text not null,

  amount_expected       numeric(14,2) not null,  -- full purchase sum the buyer is expected to pay in
  amount_received       numeric(14,2),           -- filled in by staff once confirmed on the bank statement
  date_received         date,

  status                text not null default 'awaiting_funds',
    -- awaiting_funds : reference issued to buyer, nothing received yet
    -- funds_received : staff confirmed the transfer landed, not yet reconciled/held
    -- held           : reconciled and held pending transaction completion
    -- released       : paid out to the seller (fees deducted at source), transaction complete
    -- refunded       : returned to the buyer, sale did not complete
    -- disputed       : a problem exists, do not release until resolved

  release_amount_seller numeric(14,2),   -- what the seller actually receives, after MyPlot's fees
  release_date          date,
  released_by           text,            -- staff member who authorised the release
  notes                 text,            -- free text: bank reference seen, follow-ups, disputes, etc.

  constraint escrow_status_valid
    check (status in ('awaiting_funds', 'funds_received', 'held', 'released', 'refunded', 'disputed'))
);

comment on table escrow_transactions is 'Manual staff tracking of buyer funds held pending a sale closing. Records status only, it does not move money itself, staff confirm transfers by hand against MyPlot''s real bank account until automated banking integration is added.';

-- Reference codes are generated by the database, same pattern as referral
-- codes, so two transactions started at once can never collide, and staff
-- never have to invent one by hand. Format: ESC- plus 6 characters.

create or replace function generate_escrow_reference() returns text as $$
declare
  chars text := 'ABCDEFGHJKMNPQRSTUVWXYZ23456789';
  candidate text;
  already_used boolean;
begin
  loop
    candidate := 'ESC-';
    for i in 1..6 loop
      candidate := candidate || substr(chars, floor(random() * length(chars) + 1)::int, 1);
    end loop;
    select exists(select 1 from escrow_transactions where reference_code = candidate) into already_used;
    exit when not already_used;
  end loop;
  return candidate;
end;
$$ language plpgsql;

create or replace function set_escrow_reference() returns trigger as $$
begin
  if new.reference_code is null or new.reference_code = '' then
    new.reference_code := generate_escrow_reference();
  end if;
  return new;
end;
$$ language plpgsql;

create trigger trg_set_escrow_reference
before insert on escrow_transactions
for each row execute function set_escrow_reference();


-- ============================================================================
-- ROW LEVEL SECURITY
-- ----------------------------------------------------------------------------
-- Without this section, anyone with your public "anon" key (which is visible
-- in the site's own JavaScript) could read every submission, including
-- names, phone numbers, and fraud reports. Two access levels now exist:
--   - anon (not logged in): can INSERT into the four public forms, cannot
--     read anything back.
--   - authenticated (logged in as a referrer): can additionally read their
--     OWN referrer profile, the buy_inquiries rows that carried their code,
--     and the sell_submissions rows those inquiries led to, nothing else.
-- Nobody, at either level, can read another referrer's payout details, a
-- seller's contact info, or a fraud report. Only you, via the Supabase
-- dashboard, can see everything.
-- ============================================================================

alter table check_requests      enable row level security;
alter table referrers           enable row level security;
alter table buy_inquiries       enable row level security;
alter table sell_submissions    enable row level security;
alter table fraud_reports       enable row level security;
alter table admins              enable row level security;
alter table escrow_transactions enable row level security;


-- ---- Referrer signup & dashboard access (authenticated only) ----
-- Referrers must create a Supabase Auth account first (email + password),
-- then this table stores their profile, linked one-to-one via user_id.
-- There is no anon insert policy here any more, signing up as a referrer
-- now requires being logged in, which happens the instant auth.signUp()
-- succeeds on the client.

create policy "A referrer can create their own profile"
  on referrers for insert
  to authenticated
  with check (user_id = auth.uid());

create policy "A referrer can view their own profile"
  on referrers for select
  to authenticated
  using (user_id = auth.uid());

create policy "A referrer can view inquiries that carried their code"
  on buy_inquiries for select
  to authenticated
  using (
    referral_code = (select referral_code from referrers where user_id = auth.uid())
  );

create policy "A referrer can view sales linked to their referrals"
  on sell_submissions for select
  to authenticated
  using (
    buyer_inquiry_id in (
      select id from buy_inquiries
      where referral_code = (select referral_code from referrers where user_id = auth.uid())
    )
  );

-- Note: a referrer's SELECT on sell_submissions returns whatever columns
-- the query asks for, including sale_price and referral_commission on rows
-- that belong to them, that is the point of the dashboard. It does NOT let
-- them see other sellers' rows, or any row not linked to their own code.


-- ---- Public form submissions (anonymous, insert-only) ----

create policy "Public can submit check requests"
  on check_requests for insert
  to anon
  with check (true);

create policy "Public can submit buy inquiries"
  on buy_inquiries for insert
  to anon
  with check (true);

create policy "Public can submit sell listings"
  on sell_submissions for insert
  to anon
  with check (true);

create policy "Public can submit fraud reports"
  on fraud_reports for insert
  to anon
  with check (true);

-- No SELECT / UPDATE / DELETE policies exist for the anon role at all. This
-- means the public website, before anyone logs in, can never read back
-- submissions, only Supabase's dashboard (logged in as project owner), an
-- authenticated referrer viewing their own linked rows as above, or a
-- properly authenticated admin as below, can.


-- ---- Admin access (authenticated + present in the admins table) ----
-- Full read and update across every table, for admin/index.html. Every
-- policy below checks the same thing: is this logged-in user's id present
-- in the admins table. If they are not in that table, none of these
-- policies apply to them, they fall back to the ordinary anon-level access
-- (none) or referrer-level access (their own rows only) above. Admin status
-- is never self-granted, see the admins table definition for how someone
-- actually becomes an admin.

create policy "A user can check their own admin status"
  on admins for select
  to authenticated
  using (user_id = auth.uid());

create policy "Admins can view all check requests"
  on check_requests for select to authenticated
  using (exists (select 1 from admins where user_id = auth.uid()));

create policy "Admins can update check requests"
  on check_requests for update to authenticated
  using (exists (select 1 from admins where user_id = auth.uid()));

create policy "Admins can view all sell submissions"
  on sell_submissions for select to authenticated
  using (exists (select 1 from admins where user_id = auth.uid()));

create policy "Admins can update sell submissions"
  on sell_submissions for update to authenticated
  using (exists (select 1 from admins where user_id = auth.uid()));

create policy "Admins can view all buy inquiries"
  on buy_inquiries for select to authenticated
  using (exists (select 1 from admins where user_id = auth.uid()));

create policy "Admins can update buy inquiries"
  on buy_inquiries for update to authenticated
  using (exists (select 1 from admins where user_id = auth.uid()));

create policy "Admins can view all fraud reports"
  on fraud_reports for select to authenticated
  using (exists (select 1 from admins where user_id = auth.uid()));

create policy "Admins can update fraud reports"
  on fraud_reports for update to authenticated
  using (exists (select 1 from admins where user_id = auth.uid()));

create policy "Admins can view all referrers"
  on referrers for select to authenticated
  using (exists (select 1 from admins where user_id = auth.uid()));

create policy "Admins can update referrers"
  on referrers for update to authenticated
  using (exists (select 1 from admins where user_id = auth.uid()));

create policy "Admins can view all escrow transactions"
  on escrow_transactions for select to authenticated
  using (exists (select 1 from admins where user_id = auth.uid()));

create policy "Admins can create escrow transactions"
  on escrow_transactions for insert to authenticated
  with check (exists (select 1 from admins where user_id = auth.uid()));

create policy "Admins can update escrow transactions"
  on escrow_transactions for update to authenticated
  using (exists (select 1 from admins where user_id = auth.uid()));

-- No anon policy exists on escrow_transactions at all: a transaction is only
-- ever created by a staff member on the admin page once a sale is agreed,
-- never submitted by the public.

-- Note: a referrer who is ALSO an admin (e.g. you, using your own referral
-- code) still only gets ONE set of rows back per query, Postgres does not
-- duplicate rows just because two policies both happen to allow the same
-- row. Their admin access simply widens what else becomes visible.


