-- ============================================================================
-- MYPLOT.NG — SUPABASE SCHEMA
-- ----------------------------------------------------------------------------
-- Covers the four live forms on myplot.ng (CheckMyPlot requests, SellMyPlot
-- listings, BuyMyPlot inquiries, and community fraud reports), plus the
-- referral system: anyone can sign up for a referral code (via a real
-- Supabase Auth email/password account), BUYERS enter that code when
-- submitting a BuyMyPlot inquiry, and once the listing they were inquiring
-- about actually sells, 1% of the total sale price is set aside for
-- whoever referred that buyer, paid out of MyPlot's own 5% commission so
-- buyers and sellers never pay anything extra. Referrers log into their
-- own dashboard to see only their own referral activity, never anyone
-- else's, and never a seller's or another referrer's private details.
--
-- IMPORTANT: the referral credit follows the BUYER, not the seller. A seller
-- who lists a plot earns nothing for anyone by listing it, the referral is
-- only triggered by whoever brought the buyer whose purchase closed the sale.
--
-- IMPORTANT: referral codes are generated by the database itself (see the
-- trigger in section 2B below), never chosen by the referrer and never sent
-- by the client. The signup form should not include a referral_code field.
--
-- Field names below match the actual <input name="..."> attributes already
-- live in the site's HTML, so the engineer wiring up the forms can map
-- straight from form field to column with no renaming.
--
-- HOW TO USE:
-- 1. In the Supabase dashboard, under Authentication, enable Email/Password
--    sign-in if it is not already on. This is required before referrer
--    signup can work at all.
-- 2. Open your Supabase project → SQL Editor → New query.
-- 3. Paste this whole file and run it once. It creates all tables in the
--    correct dependency order, sets up the referral code trigger, turns
--    on Row Level Security, and sets both the public submission policies
--    and the authenticated referrer dashboard policies.
-- 4. The site's forms, referrer signup, login, and dashboard pages are
--    already built and already call Supabase directly (raw REST calls to
--    /rest/v1/... and /auth/v1/..., using the public "anon" key, no SDK
--    needed). Your engineer's remaining job is to confirm the "Confirm
--    email" setting under Authentication matches what you want (default:
--    on, meaning a referrer must click a confirmation email link before
--    their first login creates their profile), then test the whole flow
--    end to end against your real Supabase project before this goes live.
-- 5. When a sale completes: an admin (via the Supabase dashboard, not the
--    public site) updates the relevant sell_submissions row: sets status to
--    'sold', fills in sale_price and buyer_inquiry_id (which buy_inquiries
--    row was the buyer who actually purchased), and myplot_commission /
--    referral_commission are then calculated from those two fields.
-- 6. You (Dr. Femi) view submissions either in the Supabase Table Editor
--    directly, or by setting up email/Slack alerts on new rows (see note
--    at the bottom of this file).
-- ============================================================================


-- ---------- 1. CHECKMYPLOT REQUESTS ----------
-- Source: check/index.html, "Request a CheckMyPlot report" form

create table check_requests (
  id              uuid primary key default gen_random_uuid(),
  created_at      timestamptz not null default now(),
  status          text not null default 'new',   -- new / in_review / completed / cancelled

  name            text not null,
  phone           text not null,
  email           text not null,
  plot_location   text not null,                 -- e.g. "Gwarinpa, Abuja"
  plot_count      text,                          -- free text, e.g. "1" or "8 for a multi plot estate"
  plot_reference  text,                          -- survey plan / plot number, if known
  addon_insight   boolean not null default false,
  addon_foresight boolean not null default false,
  details         text,                          -- seller name, documents already held, etc.

  constraint check_requests_status_valid
    check (status in ('new', 'in_review', 'completed', 'cancelled'))
);

comment on table check_requests is 'CheckMyPlot report requests submitted from check/index.html';


-- ---------- 2. REFERRERS ----------
-- Source: refer/index.html, "Become a referrer" signup form
-- Created before buy_inquiries, which references referral_code below.

create table referrers (
  id                  uuid primary key default gen_random_uuid(),
  created_at          timestamptz not null default now(),
  status              text not null default 'pending',   -- pending / active / suspended

  user_id             uuid not null unique references auth.users(id),  -- the referrer's login account
  name                text not null,
  phone               text not null,
  email               text not null,
  referral_code       text not null unique,   -- auto-generated on insert, see trigger below,
                                              -- the client never supplies this value

  bank_account_name   text,                   -- name on the bank account
  bank_account_number text,                   -- account number
  bank_name           text,                   -- e.g. "GTBank", "Access Bank"

  total_earned        numeric(14,2) not null default 0,  -- running total of paid-out referral commission

  constraint referrers_status_valid
    check (status in ('pending', 'active', 'suspended'))
);

comment on table referrers is 'People who signed up (via Supabase Auth) to refer buyers to MyPlot and earn a share of commission when that buyer''s purchase closes. One row per authenticated referrer, linked via user_id.';


-- ---------- 2B. AUTO-GENERATED REFERRAL CODES ----------
-- Codes are generated by the database itself, never by the client, so two
-- people signing up at the same instant can never be handed the same code.
-- Format: 6 characters, uppercase letters and digits, excluding 0/O/1/I/L
-- since those are easy to misread when a referrer shares their code aloud
-- or over WhatsApp.

create or replace function generate_referral_code() returns text as $$
declare
  chars text := 'ABCDEFGHJKMNPQRSTUVWXYZ23456789';
  candidate text;
  already_used boolean;
begin
  loop
    candidate := '';
    for i in 1..6 loop
      candidate := candidate || substr(chars, floor(random() * length(chars) + 1)::int, 1);
    end loop;
    select exists(select 1 from referrers where referral_code = candidate) into already_used;
    exit when not already_used;
  end loop;
  return candidate;
end;
$$ language plpgsql;

create or replace function set_referral_code() returns trigger as $$
begin
  new.referral_code := generate_referral_code();
  return new;
end;
$$ language plpgsql;

create trigger trg_set_referral_code
before insert on referrers
for each row execute function set_referral_code();

-- Note for the engineer: because this trigger always overwrites
-- referral_code on insert, the signup form must not include a
-- referral_code field at all, whatever the client sends in that column is
-- discarded anyway.


-- ---------- 3. BUYMYPLOT INQUIRIES ----------
-- Source: buy/index.html, buyer inquiry form
-- Created before sell_submissions, which references buy_inquiries(id) below
-- to record which buyer's inquiry actually led to a completed sale.

create table buy_inquiries (
  id                 uuid primary key default gen_random_uuid(),
  created_at         timestamptz not null default now(),
  status             text not null default 'new',   -- new / contacted / closed

  name               text not null,
  phone              text not null,
  email              text not null,
  preferred_location text,                          -- e.g. "Guzape, Life Camp, Jahi"
  budget_range       text,                          -- free text, e.g. "N20,000,000 to N40,000,000"
  details            text,                          -- plot size, purpose, timeline, etc.

  -- ---- Referral tracking ----
  referral_code      text references referrers(referral_code),  -- code the BUYER entered, if any

  constraint buy_status_valid
    check (status in ('new', 'contacted', 'closed'))
);

comment on table buy_inquiries is 'BuyMyPlot inquiries, routed internally to the buyer relations team, never shown directly to sellers';


-- ---------- 4. SELLMYPLOT SUBMISSIONS ----------
-- Source: sell/index.html, "Submit a listing" form

create table sell_submissions (
  id                    uuid primary key default gen_random_uuid(),
  created_at            timestamptz not null default now(),
  status                text not null default 'new',   -- new / awaiting_check / listed / sold / rejected

  name                  text not null,
  phone                 text not null,
  email                 text not null,
  property_type         text not null,                 -- 'land' | 'building'
  listing_type          text not null,                 -- 'plot' | 'estate'
  estate_plot_count     text,                          -- only relevant when listing_type = 'estate'
  listing_location      text not null,                 -- e.g. "Guzape, Abuja"
  listing_reference     text,
  seller_type           text not null,                 -- 'individual' | 'agent' | 'developer'
  details               text,                          -- documents held, asking price, timeline, etc.

  -- ---- Sale & referral tracking ----
  -- Filled in by an admin once a sale actually completes, not by the seller
  -- at listing time. The referral credit flows through buyer_inquiry_id,
  -- not from this table directly — find which buyer actually purchased,
  -- link their inquiry here, and their referral_code (if any) determines
  -- who gets paid.
  buyer_inquiry_id      uuid references buy_inquiries(id),  -- which buyer's inquiry led to this sale
  sale_price            numeric(14,2),   -- filled in once status = 'sold'
  myplot_commission     numeric(14,2),   -- 10% of sale_price, paid by the seller, filled in on sale
  buyer_legal_admin_fee numeric(14,2),   -- 5% of sale_price, paid by the buyer separately, filled in on sale
  referral_commission   numeric(14,2),   -- 1% of sale_price directly, not derived from myplot_commission,
                                         -- only if the linked buyer_inquiry had a referral_code
  referral_paid         boolean not null default false,  -- has the referrer actually been paid out

  constraint sell_status_valid
    check (status in ('new', 'awaiting_check', 'listed', 'sold', 'rejected')),
  constraint sell_property_type_valid
    check (property_type in ('land', 'building')),
  constraint sell_listing_type_valid
    check (listing_type in ('plot', 'estate')),
  constraint sell_seller_type_valid
    check (seller_type in ('individual', 'agent', 'developer'))
);

comment on table sell_submissions is 'SellMyPlot listing submissions from sell/index.html, pending CheckMyPlot before going live. Referral credit for a sale is attributed via buyer_inquiry_id, not by anything the seller entered.';


-- ---------- 5. COMMUNITY FRAUD REPORTS ----------
-- Source: report/index.html, "Report land" form
-- NOTE: this table is sensitive. The site tells reporters their identity is
-- never made public — see the RLS + access note at the bottom of this file.

create table fraud_reports (
  id            uuid primary key default gen_random_uuid(),
  created_at    timestamptz not null default now(),
  status        text not null default 'new',   -- new / investigating / resolved / dismissed

  name          text not null,
  phone         text not null,
  plot_location text not null,                 -- district, area, or nearest landmark
  agent_name    text,                          -- agent being reported, if applicable
  report_type   text not null,                 -- see check constraint below
  details       text not null,

  constraint fraud_status_valid
    check (status in ('new', 'investigating', 'resolved', 'dismissed')),
  constraint fraud_report_type_valid
    check (report_type in (
      'duplicate_sale', 'forged_title', 'disputed_claim',
      'suspicious_agent', 'other'
    ))
);

comment on table fraud_reports is 'Community fraud reports. Reporter identity must never be exposed publicly or to the person/agent being reported.';


-- ---------- 6. ADMINS ----------
-- Staff with full view/edit access to every submission across every table,
-- for the admin page (see admin/index.html). This is NOT self-service.
-- There is deliberately no public or authenticated INSERT policy on this
-- table below, a row here only ever gets created by you, directly in the
-- Supabase Table Editor, using the service role which bypasses RLS.
--
-- HOW TO ADD A NEW ADMIN:
-- 1. Have that person create an account the normal way, at refer/index.html
--    (a referrer account and an admin account are the same underlying
--    Supabase Auth login, admins table membership is what adds admin
--    powers on top, it does not replace their referrer access).
-- 2. In the Supabase dashboard, go to Authentication → Users, find their
